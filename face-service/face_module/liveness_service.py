"""Flask-side active-liveness session manager.

Adapted from the prototype's ``face_module/liveness.py`` ``LivenessService``,
but with critical differences required by the Spring session protocol:

  1. **Challenges come from Spring**, not generated by Flask.  The service
     detects when Spring replaces the challenge list (on retry) and resets
     challenge progress while preserving calibration (same person).

  2. **Bounded, isolated sessions.**  A bounded dict (max from config) with
     per-session locks.  Expired and terminal sessions are cleaned up.  One
     in-flight processing operation per session.

  3. **Per-session frame validation.**  Frame sequences must be strictly
     monotonic; duplicates or out-of-order frames are rejected.

  4. **Passive anti-spoof never overridden by challenge success.**  The
     temporal anti-spoof window is checked on every frame, before challenge
     validation.  A spoof rejection returns FAILED immediately.

The service never stores embeddings, images, or biometric data.  It processes
frames in memory and returns only a decision and a machine-readable reason.
"""
from __future__ import annotations

import enum
import logging
import time
from collections import deque
from threading import Lock
from typing import Optional

import numpy as np

from .config import Config
from .recognition import FaceDetectionError, FaceError, FaceEngine
from .antispoof import AntiSpoofEngine
from .landmarks import LandmarkAnalyzer
from .glasses import GlassesGate

_log = logging.getLogger(__name__)


class Decision(enum.Enum):
    """Maps directly to Spring's ``ActiveLivenessEvaluator.Decision``."""
    PENDING = "PENDING"
    RETRYABLE_FAILURE = "RETRYABLE_FAILURE"
    FAILED = "FAILED"
    PASSED = "PASSED"


class LivenessSession:
    """Per-session active-liveness state.

    All mutable state is confined to a single session.  No global mutable
    state is shared between sessions.  A ``Lock`` serialises frame processing.
    """

    def __init__(self, session_id: str, challenge_seq: list[str],
                 config: Config, clock):
        self.session_id = session_id
        self.challenge_seq: list[str] = list(challenge_seq)
        self.config = config
        self._clock = clock
        self.created_at = clock()
        self.expires_at = self.created_at + config.liveness_session_timeout_seconds

        # State machine: CALIBRATING -> CHALLENGE -> terminal
        self.state = "CALIBRATING"
        self.terminal = False
        self.terminal_at: Optional[float] = None

        # Calibration
        self._calibration_yaws: list[float] = []
        self.neutral_yaw: Optional[float] = None

        # Challenge tracking
        self.current_challenge_idx = 0
        self._blink_phase = "OPEN"       # OPEN -> CLOSED -> CONFIRMED
        self._blink_smooth: Optional[tuple[float, float]] = None
        self._blink_closed_frames = 0
        self._turn_stable = 0

        # Temporal passive anti-spoof
        self._spoof_scores: deque[float] = deque(maxlen=config.anti_spoof_window)

        # Glasses gate
        self.glasses = GlassesGate()

        # Frame validation
        self._last_frame_seq: Optional[int] = None

        self.lock = Lock()

    @property
    def is_expired(self) -> bool:
        return self._clock() >= self.expires_at

    def update_challenge_seq(self, new_seq: list[str]) -> None:
        """Detect Spring retry with new challenges; reset challenge progress.

        Calibration is preserved because the person has not changed.
        """
        new_list = list(new_seq)
        if new_list != self.challenge_seq:
            self.challenge_seq = new_list
            self.current_challenge_idx = 0
            self._reset_challenge_state()
            _log.info("[Liveness] session=%s challenge_seq changed -> reset progress", self.session_id)

    def _reset_challenge_state(self) -> None:
        self._blink_phase = "OPEN"
        self._blink_smooth = None
        self._blink_closed_frames = 0
        self._turn_stable = 0

    def _mark_terminal(self) -> None:
        """Record the time at which the session reached a terminal state."""
        self.terminal = True
        self.terminal_at = self._clock()

    def process(self, landmark_frame, anti_spoof_score: Optional[float],
                frame_seq: int) -> tuple[Decision, Optional[str]]:
        """Process one frame.  Must be called with ``self.lock`` held.

        Returns ``(Decision, reason)``.  ``reason`` is a short machine-readable
        string or None.
        """
        if self.terminal:
            return Decision.FAILED, "SESSION_TERMINATED"

        # Expiry
        if self.is_expired:
            self._mark_terminal()
            return Decision.FAILED, "SESSION_EXPIRED"

        # Frame sequence validation: strictly monotonic, no duplicates
        if self._last_frame_seq is not None and frame_seq <= self._last_frame_seq:
            return Decision.RETRYABLE_FAILURE, "OUT_OF_ORDER_FRAME"
        self._last_frame_seq = frame_seq

        # Glasses detection is advisory/diagnostic only — it does NOT reject
        # the session.  The blink and head-pose challenges remain the primary
        # liveness gate.  Glasses state is tracked for future UX guidance but
        # has no effect on the liveness decision.
        self.glasses.observe(
            landmark_frame.glasses_score,
            landmark_frame.eye_region_quality,
            landmark_frame.bridge_region_score,
        )

        # Temporal passive anti-spoof: accumulate, then check mean.
        # When the development bypass is active, anti_spoof_score is None — the
        # temporal check is skipped entirely.  No fabricated score is inserted;
        # the _spoof_scores deque stays empty and no threshold comparison runs.
        if anti_spoof_score is not None:
            self._spoof_scores.append(anti_spoof_score)
            if len(self._spoof_scores) >= self.config.anti_spoof_window:
                if float(np.mean(self._spoof_scores)) < self.config.liveness_threshold:
                    self._mark_terminal()
                    return Decision.FAILED, "SPOOF_DETECTED"

        # Calibration phase
        if self.state == "CALIBRATING":
            self._calibration_yaws.append(landmark_frame.yaw)
            if len(self._calibration_yaws) >= self.config.calibration_frames:
                self.neutral_yaw = float(np.median(self._calibration_yaws))
                self.state = "CHALLENGE"
                _log.info("[Liveness] session=%s calibration done neutral_yaw=%.1f",
                          self.session_id, self.neutral_yaw)
            return Decision.PENDING, None

        # Challenge phase
        if self.state == "CHALLENGE":
            if self.current_challenge_idx >= len(self.challenge_seq):
                self._mark_terminal()
                return Decision.PASSED, "ACTIVE_LIVENESS_PASSED"

            challenge = self.challenge_seq[self.current_challenge_idx]
            if self._check_challenge(challenge, landmark_frame):
                self.current_challenge_idx += 1
                self._reset_challenge_state()
                if self.current_challenge_idx >= len(self.challenge_seq):
                    self._mark_terminal()
                    return Decision.PASSED, "ACTIVE_LIVENESS_PASSED"
                _log.info("[Liveness] session=%s challenge %d/%d passed",
                          self.session_id, self.current_challenge_idx, len(self.challenge_seq))
            return Decision.PENDING, None

        return Decision.PENDING, None

    def _check_challenge(self, challenge: str, frame) -> bool:
        if challenge == "BLINK":
            return self._check_blink(frame)
        if challenge in ("TURN_LEFT", "TURN_RIGHT"):
            return self._check_turn(challenge, frame)
        return False

    def _check_blink(self, frame) -> bool:
        """Detect OPEN -> CLOSED -> OPEN pattern using smoothed blendshape values."""
        if self._blink_smooth is None:
            self._blink_smooth = (frame.blink_left, frame.blink_right)
        else:
            s = self._blink_smooth
            self._blink_smooth = (
                0.45 * frame.blink_left + 0.55 * s[0],
                0.45 * frame.blink_right + 0.55 * s[1],
            )
        # Eyes-open baseline is ~0 during calibration (neutral pose, eyes open).
        closed = min(self._blink_smooth) > 0.30
        opened = max(self._blink_smooth) < 0.16

        if self._blink_phase == "OPEN" and closed:
            self._blink_phase = "CLOSED"
            self._blink_closed_frames = 1
        elif self._blink_phase == "CLOSED":
            self._blink_closed_frames += 1
            if opened and self._blink_closed_frames >= 2:
                self._blink_phase = "CONFIRMED"
                return True
        return False

    def _check_turn(self, challenge: str, frame) -> bool:
        """Require 3 consecutive frames with yaw deviating > 12 deg from neutral."""
        if self.neutral_yaw is None:
            return False
        relative = frame.yaw - self.neutral_yaw
        wanted = -1 if challenge == "TURN_LEFT" else 1
        if wanted * relative > 12:
            self._turn_stable += 1
            if self._turn_stable >= 3:
                return True
        else:
            self._turn_stable = 0
        return False


class LivenessService:
    """Flask-side active-liveness session manager.

    Bounded in-memory session store.  Thread-safe via per-session locks.
    Accepts Spring-provided challenge sequences; never generates its own.
    Single-instance deployment assumption (documented in README.md).
    """

    def __init__(self, config: Config, engine: FaceEngine,
                 landmarks: LandmarkAnalyzer, anti_spoof: AntiSpoofEngine,
                 clock=None):
        self.config = config
        self.engine = engine
        self.landmarks = landmarks
        self.anti_spoof = anti_spoof
        self._clock = clock or time.monotonic
        self._sessions: dict[str, LivenessSession] = {}
        self._lock = Lock()

    def process_frame(self, session_id: str, challenge_seq: list[str],
                      frame_seq: int, image: np.ndarray) -> tuple[Decision, Optional[str]]:
        """Process one frame for a session.

        Parameters
        ----------
        session_id : str
            Spring's opaque session ID.
        challenge_seq : list[str]
            The full challenge list from Spring (e.g. ["BLINK", "TURN_LEFT"]).
            Flask detects changes and resets challenge progress.
        frame_seq : int
            Monotonic frame sequence from Spring.
        image : np.ndarray
            Decoded BGR image.

        Returns (Decision, reason) matching Spring's evaluator interface.
        """
        # Acquire or create session under dict lock
        with self._lock:
            self._cleanup()
            session = self._sessions.get(session_id)
            if session is None:
                if len(self._sessions) >= self.config.max_liveness_sessions:
                    return Decision.FAILED, "CAPACITY_UNAVAILABLE"
                session = LivenessSession(session_id, challenge_seq, self.config, self._clock)
                self._sessions[session_id] = session
            else:
                session.update_challenge_seq(challenge_seq)

        # Process under per-session lock (one in-flight per session)
        with session.lock:
            # 1. Detect exactly one face
            try:
                face_info = self.engine.detect_single_face_with_box(image)
            except FaceDetectionError as e:
                reason = "NO_FACE" if e.reason == "NO_FACE" else "MULTIPLE_FACES"
                return Decision.RETRYABLE_FAILURE, reason
            except FaceError:
                return Decision.RETRYABLE_FAILURE, "DETECTION_FAILED"

            # 2. Quality gate (blur, brightness, face ratio)
            quality_reason = self.anti_spoof.check_quality(image, face_info[:4])
            if quality_reason is not None:
                return Decision.RETRYABLE_FAILURE, quality_reason

            # 3. Passive anti-spoof score (for temporal window).
            #    When the development-only bypass is active, MiniFASNet inference
            #    is skipped entirely — no ONNX calls, no fabricated score.  The
            #    score is None, and LivenessSession.process() skips the temporal
            #    anti-spoof check accordingly.  Production always runs MiniFASNet.
            if self.config.disable_passive_antispoof:
                anti_spoof_score = None
            else:
                if not self.anti_spoof.available:
                    return Decision.FAILED, "ANTISPOOF_UNAVAILABLE"
                anti_spoof_score = self.anti_spoof.score(image, face_info)

            # 4. MediaPipe landmarks
            if not self.landmarks.available:
                return Decision.FAILED, "LANDMARKS_UNAVAILABLE"
            try:
                landmark_frame = self.landmarks.analyze(image)
            except RuntimeError:
                return Decision.RETRYABLE_FAILURE, "LANDMARKS_UNAVAILABLE"

            # 5. Liveness state machine
            return session.process(landmark_frame, anti_spoof_score, frame_seq)

    def _cleanup(self) -> None:
        """Remove terminal sessions past retention and long-abandoned sessions.

        Called under dict lock.  Recently expired sessions are NOT removed —
        ``process()`` must have a chance to return FAILED/EXPIRED for them.
        """
        now = self._clock()
        retention = self.config.terminal_retention_seconds
        to_remove = []
        for sid, s in self._sessions.items():
            if s.terminal:
                # Terminal sessions are kept for the retention period.
                if s.terminal_at is not None and now >= s.terminal_at + retention:
                    to_remove.append(sid)
            elif now >= s.expires_at + retention:
                # Non-terminal but expired long ago — abandoned session.
                to_remove.append(sid)
        for sid in to_remove:
            del self._sessions[sid]

    def get_session_count(self) -> int:
        with self._lock:
            self._cleanup()
            return len(self._sessions)
